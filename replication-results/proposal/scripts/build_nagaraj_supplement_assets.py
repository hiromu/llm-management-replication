"""Export the nine frozen focal results; never refit or rescore the study."""
import argparse
import csv
import hashlib
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--study", type=Path, default=ROOT.parent / "studies/nagaraj2021")
args = parser.parse_args()
study = args.study
out = ROOT / "supplement_assets/generated"
out.mkdir(parents=True, exist_ok=True)
claims_path = study / "reports/data/claim_outcomes.csv"
figure_data_path = study / "reports/figures/figure_focal_influence.csv"
rules_path = study / "scoring/scoring_rules_v1.json"
summary_path = study / "runs/run_20261101_v1/scoring/final_summary.json"
figure_path = study / "reports/figures/figure_focal_influence.png"
with claims_path.open() as f:
    claims = {r["unit"]: r for r in csv.DictReader(f)}
with figure_data_path.open() as f:
    plotted = {r["unit"]: r for r in csv.DictReader(f)}
order = json.loads(rules_path.read_text())["paper_level"]["paper_focal_claims"]
summary = json.loads(summary_path.read_text())
assert len(order) == 9 and summary["paper_level"] == "indeterminate"
assert sum(summary["outcomes"].values()) == len(claims) == 84
labels = {
    "T3|(3)": "T3(3) Follow-on",
    "T3|(4)": "T3(4) Follow-on",
    "T3|(5)": "T3(5) Contributors",
    "T3|(6)": "T3(6) Contributors",
    "T4|(3)": "T4(3) Follow-on",
    "T4|(4)": "T4(4) Follow-on",
    "T4|(5)": "T4(5) Contributors",
    "T4|(6)": "T4(6) Contributors",
    "T6|(1) Treat": "T6(1) Routing error",
}
outcomes = {
    "consistent": "Consistent",
    "fragile_inference": "Fragile inference",
    "indeterminate": "Indeterminate",
    "discrepant_not_fully_verified": "Discrepant, unverified",
}
tex = [
    "% Generated by scripts/build_nagaraj_supplement_assets.py from frozen result exports.",
    r"\begin{table}[H]\centering\footnotesize",
    r"\setlength{\tabcolsep}{3pt}",
    r"\begin{tabularx}{\linewidth}{@{}>{\raggedright\arraybackslash}p{3.5cm}rrrY>{\raggedright\arraybackslash}p{2.3cm}@{}}\toprule",
    r"Claim & Published (SE) & Rebuilt (SE) & $p$ & $N$: published / rebuilt & Outcome\\\midrule",
]
export = []
for key in order:
    row, point = claims[key], plotted[key]
    assert row["paper_focal"] == "True"
    assert row["final_outcome"] == point["outcome"]
    assert summary["paper_focal"][key].startswith(row["final_outcome"])
    assert abs(float(row["estimate"]) - float(point["reconstructed"])) < 1e-10
    se_key, p_key = ("se_hc1", "p_hc1") if row["benchmark"] == "HC1" else ("se_cluster", "p_cluster")
    pvalue = float(row[p_key])
    assert abs(pvalue - float(point["p_reconstructed"])) < 1e-10
    ptext = r"$<.001$" if pvalue < .001 else f"{pvalue:.3f}"
    pub = f"${float(row['published_value']):.4f}$ ({float(row['published_se']):.4f})"
    rebuilt = f"${float(row['estimate']):.4f}$ ({float(row[se_key]):.4f})"
    n = f"{int(float(row['published_N'])):,} / {int(float(row['N'])):,}"
    tex.append(" & ".join([labels[key], pub, rebuilt, ptext, n, outcomes[row["final_outcome"]]]) + r"\\")
    export.append(row)
tex.extend([
    r"\bottomrule\end{tabularx}",
    r"\caption{Nagaraj (2021): nine paper-focal claims under the frozen study-specific rules.}\label{tab:nagaraj-focal}",
    r"\end{table}",
    r"{\footnotesize T3 denotes difference-in-differences models; columns 4 and 6 include controls. T4 denotes county cross-sections for 2008--2014 (columns 3 and 5) or 2014 (columns 4 and 6). T6 uses address pairs. Rebuilt SEs and two-sided $p$-values use county-clustered CR1 for T3 and T6, and HC1 for T4. Values are from the agreeing A--B implementation pair. Outcome labels also depend on sample reconstruction, printed-value consistency, and uncertain specifications, not only on the displayed coefficient and $p$-value. Unverified means the discrepancy survived review within the implementation model families but has not received independent-family or human verification.}",
])
(out / "nagaraj2021_focal.tex").write_text("\n".join(tex) + "\n")
with (out / "nagaraj2021_focal.csv").open("w", newline="") as f:
    writer = csv.DictWriter(f, fieldnames=list(export[0]))
    writer.writeheader()
    writer.writerows(export)
shutil.copy2(figure_path, ROOT / "supplement_assets/nagaraj2021.png")
shutil.copy2(figure_data_path, out / "nagaraj2021_influence.csv")
sources = [claims_path, figure_data_path, rules_path, summary_path, figure_path]
(out / "nagaraj2021_provenance.json").write_text(json.dumps({
    "study": "nagaraj2021", "run": "run_20261101_v1",
    "sources": {str(p.relative_to(study)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sources},
    "human_review": "none performed", "rescoring_or_refitting": False,
}, indent=2) + "\n")
print("Exported nine verified focal rows, original figure, influence data, and source hashes.")
